export function apfsCaseFold(text) {
    let folded = '';
    for (const ch of text.normalize('NFD')) {
        const cp = ch.codePointAt(0);
        let mapped = exceptions.get(cp);
        if (mapped === undefined) {
            mapped = ch;
            for (const [first, last, stride, delta] of ranges) {
                if (cp < first) break;
                if (cp <= last && (cp - first) % stride === 0) {
                    mapped = String.fromCodePoint(cp + delta);
                    break;
                }
            }
        }
        folded += mapped;
    }
    // Folding can introduce combining marks, so normalize again afterwards.
    return folded.normalize('NFD');
}
