// C ref: version.c:280 early_version_info(pastebuf) — the `--version` command
// line answer, printed before the window system exists, so it splits the
// " (git info)" tail onto its own line by hand.  RUNTIME_PASTEBUF_SUPPORT is
// not defined for this build.
export async function early_version_info(pastebuf) {
    let buf1 = 'test', buf2, buf;

    /* this is early enough that we have to do our own line-splitting */
    buf1 = getversionstring(buf1, BUFSZ);
    const tmpIdx = buf1.indexOf(' (');  /* split at start of version info */
    if (tmpIdx >= 0) {
        /* retain one buffer so that it all goes into the paste buffer */
        buf2 = `${buf1.slice(0, tmpIdx)}\n${buf1.slice(tmpIdx + 1)}`;
        buf = buf2;
    } else {
        buf = buf1;
    }

    // js/end.js neither defines nor exports raw_printf, so this destructure
    // yielded undefined and the whole `--version` path threw
    // `TypeError: raw_printf is not a function` on every call.  pline.c is its
    // C home and js/pline.js now has it.  Note that pline.js's raw_print() is
    // still a module-local accumulator, as are the copies in js/report.js:42,
    // js/options.js:602 and js/topten.js:335 -- none of the four reaches the
    // tty, so this path is correctly shaped but does not draw.
    const { raw_printf } = await import('./pline.js');
    raw_printf('%s', buf);

    if (pastebuf) {
        raw_printf('%s', 'Paste buffer copy is not available.\n');
    }
}

