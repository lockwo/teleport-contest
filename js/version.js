// C ref: hacklib.c eos(s) / files.c nh_basename(fname, keep_suffix).
function nh_basename(fname, keep_suffix) {
    if (!fname) return '';
    let p = fname.lastIndexOf('/');
    if (p >= 0) fname = fname.slice(p + 1);
    p = fname.lastIndexOf('.');
    if (p >= 0 && !keep_suffix) fname = fname.slice(0, p);
    return fname;
}

// C ref: version.c:22 version_string(buf, bufsz) — the SHORT "x.y.z" form.
// The mdlib_version_string() fallback exists for paniclog entries written after
// release_runtime_info() has dropped the 'nomakedefs' strings.
export function version_string(buf, bufsz) {
    void buf; void bufsz;
    return (nomakedefs.version_string && nomakedefs.version_string[0])
        ? nomakedefs.version_string
        : mdlib_version_string(buf, '.');
}

// C ref: version.c:35 getversionstring(buf, bufsz) — nomakedefs.version_id plus
// a parenthesised list of whatever git/port info the build has.  For this build
// git_sha/git_branch/git_prefix are all NULL and RUNTIME_PORT_ID is undefined,
// so c stays 0, the " (" is stripped back off and the trailing '.' is restored.
export function getversionstring(buf, bufsz) {
    void buf; void bufsz;
    let out = String(nomakedefs.version_id ?? '');

    {
        let c = 0;
        const dotoff = out.length > 0 && out[out.length - 1] === '.';

        if (dotoff) out = out.slice(0, -1);   /* --p past the '.' */
        const p = out.length;                 /* index of the " (" we add */
        out += ' (';
        /* RUNTIME_PORT_ID: get_port_id() is not compiled in for this build */
        if (nomakedefs.git_sha)
            out += `${c++ ? ',' : ''}${nomakedefs.git_sha}`;
        /* NH_DEVEL_STATUS == NH_STATUS_RELEASED, so the branch arm is out */
        if (nomakedefs.git_prefix)
            out += `${c++ ? ',' : ''}prefix:${nomakedefs.git_prefix}`;
        if (c)
            out += ')';
        else /* if nothing has been added, strip " (" back off */
            out = out.slice(0, p);
        if (dotoff)
            out += '.';
    }
    return out;
}

// C ref: version.c:89 status_version(buf, bufsz, indent) — the 'showvers'
// status-line text: game name and/or branch name and/or x.y.z, per
// flags.versinfo.  With no git branch, showbranch is forced off.
export function status_version(buf, bufsz, indent) {
    void buf; void bufsz;
    let name = null, altname = null, indentation;
    const vflags = game.flags?.versinfo | 0;
    let shownum = ((vflags & VI_NUMBER) !== 0),
        showname = ((vflags & VI_NAME) !== 0),
        showbranch = ((vflags & VI_BRANCH) !== 0);

    /* game's name {variants should use own name, not "NetHack"} */
    if (showname) {
        /* VERS_GAME_NAME is not defined, so it is basename(gh.hname) */
        name = nh_basename(game.hname ?? HNAME_DEFAULT, false);
        if (!name || !name[0]) /* shouldn't happen */
            showname = false;
    }
    /* git branch name, if available */
    if (showbranch) {
        altname = nomakedefs.git_branch;
        if (!altname || !altname[0])
            showbranch = false;
    }
    if (showname && showbranch) {
        if (altname.slice(0, name.length).toLowerCase() === name.toLowerCase())
            showname = false;
    } else if (!showname && !showbranch) {
        /* flags.versinfo could be set to only 'branch' but it might not
           be available */
        shownum = true;
    }

    let out = '';
    indentation = indent ? ' ' : '';
    if (showname) {
        out += `${indentation}${name}`;
        indentation = ' '; /* forced separator rather than optional indent */
    }
    if (showbranch) {
        out += `${indentation}${altname}`;
        indentation = ' ';
    }
    if (shownum) {
        /* x.y.z version number */
        out += indentation
            + ((nomakedefs.version_string && nomakedefs.version_string[0])
               ? nomakedefs.version_string
               : mdlib_version_string(buf, '.'));
    }
    return out;
}

