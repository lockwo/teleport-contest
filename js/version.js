// C ref: version.c:339 insert_rtoption(buf) — substitute every ":TOKEN:" on the
// line; there may be more than one, so the loop does not break on a match.
//
// !gl.lua_ver[0] -> get_lua_version(), which builds a Lua state and therefore
// runs nhlib.lua's top-level shuffle(align): rn2(3) then rn2(2), once per
// process.  ensure_lua_version_loaded() above is that same one-shot.
export function insert_rtoption(buf) {
    let i;

    if (!game.luaVersionCached)
        ensure_lua_version_loaded();

    for (i = 0; i < rt_opts.length; ++i) {
        const val = rt_opts[i].value();
        if (buf.includes(rt_opts[i].token) && val)
            buf = buf.replace(rt_opts[i].token, val);
        /* we don't break out of the loop after a match; there might be
           other matches on the same line */
    }
    return buf;
}

// C ref: version.c:357 comp_times(filetime) — MICRO-only "is this file older
// than the binary?" test.  The comparison is unsigned in C.
export function comp_times(filetime) {
    /* BUILD_TIME is constant but might have L suffix rather than UL;
       'filetime' is historically signed but ought to have been unsigned */
    return (filetime >>> 0) < (nomakedefs.build_time >>> 0);
}

// C ref: version.c:374 check_version(version_data, filename, complain,
// utdflags) — compare a save/bones file's three version words against ours.
// VERSION_COMPATIBILITY is undefined for this build, so the incarnation must
// match exactly.
export async function check_version(version_data, filename, complain, utdflags) {
    if (!filename) {
        complain = false; /* 'complain' requires 'filename' for pline("%s") */
    }
    if ((version_data.feature_set & SFCTOOL_BIT) !== 0) {
        game.converted_savefile_loaded = true;
        version_data.feature_set &= ~SFCTOOL_BIT;
    }
    if (version_data.incarnation !== nomakedefs.version_number) {
        if (complain) {
            const { pline } = await import('./display.js');
            await pline(`Version mismatch for file "${filename}".`);
        }
        return false;
    } else if (
        ((version_data.feature_set & ~nomakedefs.ignored_features) >>> 0)
            !== ((nomakedefs.version_features & ~nomakedefs.ignored_features) >>> 0)
        || (((utdflags & UTD_SKIP_SANITY1) === 0)
             && version_data.entity_count !== nomakedefs.version_sanity1)
        ) {
        if (complain) {
            const { pline } = await import('./display.js');
            await pline(`Configuration incompatibility for file "${filename}".`);
        }
        return false;
    }
    return true;
}

// C ref: version.c:464 get_current_feature_ver() — FEATURE_NOTICE_VER of the
// running binary, used to reject a 'suppress_alert' newer than we are.
// hack.h:1504 FEATURE_NOTICE_VER(maj,min,patch).
export function get_current_feature_ver() {
    return (((VERSION_MAJOR << 24) | (VERSION_MINOR << 16)
             | (PATCHLEVEL << 8) | 0) >>> 0);
}

// C ref: version.c:494 dump_version_info() — the `--dumpversion` answer that
// argcheck() prints and exits on: program name plus the three save-file words
// in hex.  Snprintf's "%-12.33s" left-justifies to 12 and truncates at 33.
export async function dump_version_info() {
    let hname = game.hname ? game.hname : 'nethack';

    if (hname.length > 33)
        hname = hname.slice(hname.length - 33);
    runtime_info_init();
    const hex8 = (n) => (n >>> 0).toString(16).padStart(8, '0');
    /* version_sanity1 exceeds 32 bits, so format it without the >>> 0 clamp */
    const hexN = (n) => Math.trunc(n).toString(16).padStart(8, '0');
    const buf = `${hname.slice(0, 33).padEnd(12, ' ')} `
        + `${hexN(nomakedefs.version_number)} `
        + `${hex8(nomakedefs.version_features & ~nomakedefs.ignored_features)} `
        + `${hexN(nomakedefs.version_sanity1)}`;
    const { raw_print } = await import('./end.js');
    raw_print(buf);
    release_runtime_info();
    return;
}

// C ref: version.c:512 store_version(nhfp) — the first thing written to any
// save/bones/level file: the critical-size bytes then the version_info struct,
// both outside the buffered-write window.  js/storage.js is frozen and owns its
// own format, so Sfo_version_info() just appends the record to nhfp.
export function store_version(nhfp) {
    const version_data = { incarnation: 0, feature_set: 0, entity_count: 0 };

    /* actual version number */
    version_data.incarnation = nomakedefs.version_number;
    /* bitmask of config settings */
    version_data.feature_set = nomakedefs.version_features;
    /* # of monsters and objects */
    version_data.entity_count = nomakedefs.version_sanity1;

    /* bwrite() before bufon() uses plain write() */
    if (nhfp?.structlevel) bufoff(nhfp.fd);

    store_critical_bytes(nhfp);
    Sfo_version_info(nhfp, version_data, 'version_info');

    if (nhfp?.structlevel) bufon(nhfp.fd);
    return;
}

