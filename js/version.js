// C ref: version.c:676 store_critical_bytes(nhfp) — a format indicator, the
// count, then one byte per critical size.  Only on a WRITING pass.
export function store_critical_bytes(nhfp) {
    let i, cnt;
    let indicate = 'u';
    const csc_count = critical_sizes.length;

    if ((nhfp?.mode | 0) & WRITING) {
        indicate = (nhfp.structlevel) ? 'h'
                 : (nhfp.fnidx === exportascii) ? 'a'
                 : '?';
        Sfo_char(nhfp, indicate, 'indicate-format', 1);
        Sfo_char(nhfp, csc_count, 'count-critical_sizes', 1);
        cnt = csc_count;
        for (i = 0; i < cnt; ++i) {
            Sfo_uchar(nhfp, critical_sizes[i].ucsize, 'critical_sizes');
        }
    }
}

// C ref: version.c:713 uptodate(nhfp, name, utdflags) — read the critical bytes
// and the version_info struct off the front of a file and decide whether this
// binary can read the rest.  See the SF_* table for the return codes.
export async function uptodate(nhfp, name, utdflags) {
    const vers_info = { incarnation: 0, feature_set: 0, entity_count: 0 };
    let indicator;
    let sfstatus = 0;
    const idx_1st_mismatch = { value: 0 };
    const quietly = (utdflags & UTD_QUIETLY) !== 0;
    const verbose = name ? true : false;

    indicator = Sfi_char(nhfp, 'indicate-format', 1);
    void indicator;
    if ((sfstatus = compare_critical_bytes(nhfp, idx_1st_mismatch, utdflags))
                                                            !== SF_UPTODATE) {
        if (sfstatus > 0 && idx_1st_mismatch.value) {
            if (!quietly)
                raw_printf_local(
                    `comparison of critical bytes mismatched at `
                    + `${critical_sizes[idx_1st_mismatch.value].ucsize} `
                    + `(${critical_sizes[idx_1st_mismatch.value].nm}).`);
        }
    }

    Sfi_version_info(nhfp, vers_info, 'version_info');
    if (!(await check_version(vers_info, name, verbose, utdflags))) {
        if (verbose) {
            if ((utdflags & UTD_WITHOUT_WAITSYNCH_PERFILE) === 0) {
                wait_synch_local();
            }
        }
        return SF_OUTDATED;
    }
    return sfstatus;
}

// C ref: version.c:763 compare_critical_bytes(nhfp, idx_1st_mismatch, utdflags)
// — byte-for-byte compare of the file's sizeof table against ours, naming the
// data-model pair when the first five (short/int/long/long long/ptr) explain it.
export function compare_critical_bytes(nhfp, idx_1st_mismatch, utdflags) {
    const active_csc_count = critical_sizes.length;
    let file_csc_count;
    let i, cnt = active_csc_count, dmmismatch = SF_DM_MISMATCH;
    const quietly = (utdflags & UTD_QUIETLY) !== 0;

    file_csc_count = Sfi_char(nhfp, 'count-critical_sizes', 1);
    if (file_csc_count > cnt) {
        if (!quietly)
            raw_printf_local('critical byte counts do not match'
                             + `, file:${file_csc_count}`
                             + `, critical_sizes:${critical_sizes.length}.`);
        return SF_CRITICAL_BYTE_COUNT_MISMATCH;
    }
    for (i = 0; i < file_csc_count; ++i) {
        cscbuf[i] = Sfi_uchar(nhfp, 'critical_sizes');
    }
    for (i = 1; i < cnt; ++i) {
        if (cscbuf[i] !== critical_sizes[i].ucsize) {
            const dm = datamodel(0);
            const dmfile = what_datamodel_is_this(0,
                                                  cscbuf[1],  /* short */
                                                  cscbuf[2],  /* int */
                                                  cscbuf[3],  /* long */
                                                  cscbuf[4],  /* long long */
                                                  cscbuf[5]); /* ptr */

            if (dmfile === 'IL32LLP64' && dm === 'ILP32LL64') {
                /*  Windows x64 savefile on x86 */
                dmmismatch = SF_DM_IL32LLP64_ON_ILP32LL64;
            } else if (dmfile === 'I32LP64' && dm === 'ILP32LL64') {
                /* Unix 64 savefile on x86*/
                dmmismatch = SF_DM_I32LP64_ON_ILP32LL64;
            } else if (dmfile === 'ILP32LL64' && dm === 'I32LP64') {
                /*  x86 savefile on Unix 64 */
                dmmismatch = SF_DM_ILP32LL64_ON_I32LP64;
            } else if (dmfile === 'ILP32LL64' && dm === 'IL32LLP64') {
                /* x86 savefile on Windows x64 */
                dmmismatch = SF_DM_ILP32LL64_ON_IL32LLP64;
            } else if (dmfile === 'I32LP64' && dm === 'IL32LLP64') {
                /* Unix 64 savefile on Windows x64 */
                dmmismatch = SF_DM_I32LP64_ON_IL32LLP64;
            } else if (dmfile === 'IL32LLP64' && dm === 'I32LP64') {
                /* Windows x64 savefile on Unix 64 */
                dmmismatch = SF_DM_IL32LLP64_ON_I32LP64;
            }
            if (idx_1st_mismatch)
                idx_1st_mismatch.value = i;
            return dmmismatch;
        }
    }
    return SF_UPTODATE; /* everything matched */
}

// C ref: version.c:840 validate(nhfp, name, without_waitsynch_perfile) — the
// wrapper every file-open path uses; it derives utdflags from how the file is
// marshalled (struct-level vs field-level) and calls uptodate().
export async function validate(nhfp, name, without_waitsynch_perfile) {
    let utdflags = 0;
    let validsf = 0;

    if (nhfp?.structlevel) utdflags |= UTD_CHECKSIZES;
    if (without_waitsynch_perfile) utdflags |= UTD_WITHOUT_WAITSYNCH_PERFILE;
    if (nhfp?.fieldlevel) utdflags |= UTD_CHECKFIELDCOUNTS | UTD_SKIP_SANITY1;
    validsf = await uptodate(nhfp, name, utdflags);
    return validsf;
}

// ── local stand-ins for collaborators outside this file ──
// hacklib.c datamodel(0) / what_datamodel_is_this(): the recorder's build is
// I32LP64 (short 2, int 4, long 8, long long 8, ptr 8).
const DM_TABLE = [
    { sz: [2, 4, 4, 8, 4], datamodel: 'ILP32LL64', dmplatform: 'x86 32-bit' },
    { sz: [2, 4, 4, 8, 8], datamodel: 'IL32LLP64', dmplatform: 'Windows x64 64-bit' },
    { sz: [2, 4, 8, 8, 8], datamodel: 'I32LP64', dmplatform: 'Unix 64-bit' },
    { sz: [2, 8, 8, 8, 8], datamodel: 'ILP64', dmplatform: 'Unix ILP64' },
];
function datamodel(retidx) {
    return what_datamodel_is_this(retidx, 2, 4, 8, 8, 8);
}
function what_datamodel_is_this(retidx, szshort, szint, szlong, szll, szptr) {
    for (const e of DM_TABLE)
        if (szshort === e.sz[0] && szint === e.sz[1] && szlong === e.sz[2]
            && szll === e.sz[3] && szptr === e.sz[4])
            return (retidx === 0) ? e.datamodel : e.dmplatform;
    return 'Unknown';
}
// sfbase.c Sfo_/Sfi_ marshalling is coverage-N/A: js/storage.js is frozen and
// owns the save format, so these append to / read from whatever record list the
// caller's nhfp carries.
function Sfo_char(nhfp, val, tag, _len) {
    if (nhfp && Array.isArray(nhfp.records)) nhfp.records.push({ tag, val });
}
function Sfo_uchar(nhfp, val, tag) {
    if (nhfp && Array.isArray(nhfp.records)) nhfp.records.push({ tag, val });
}
function Sfo_version_info(nhfp, vi, tag) {
    if (nhfp && Array.isArray(nhfp.records))
        nhfp.records.push({ tag, val: { ...vi } });
}
function Sfi_char(nhfp, tag, _len) {
    const r = nhfp?.records?.shift();
    return (r && r.tag === tag) ? r.val : 0;
}
function Sfi_uchar(nhfp, tag) {
    const r = nhfp?.records?.shift();
    return (r && r.tag === tag) ? r.val : 0;
}
function Sfi_version_info(nhfp, vi, tag) {
    const r = nhfp?.records?.shift();
    if (r && r.tag === tag && r.val) Object.assign(vi, r.val);
}
